def _build() -> dict:
    clusters: dict = {}
    for key, (cid, name) in _META.items():
        words = list(_TERMS[key])
        if not words:
            raise SystemExit(f"{key} has no terms")
        folded = [w.casefold() for w in words]
        if len(set(folded)) != len(words):
            raise SystemExit(f"{key} duplicate terms")
        clusters[key] = {"id": cid, "name": name, "words": words}
    ids = [m["id"] for m in clusters.values()]
    names = [m["name"] for m in clusters.values()]
    if len(ids) != len(set(ids)):
        raise SystemExit("duplicate ids")
    if len(names) != len(set(names)):
        raise SystemExit("duplicate names")
    missing = []
    blob = " | ".join(w.casefold() for m in clusters.values() for w in m["words"])
    for term in MUST:
        if term.casefold() not in blob:
            missing.append(term)
    if missing:
        raise SystemExit("missing must-have: " + "; ".join(missing))
    return clusters


CLUSTERS = _build()


def lookup(article: dict) -> dict:
    hub = article["hub"]
    if hub == "both":
        hub = "fl"
    return CLUSTERS[(hub, article["cluster"])]


def validate() -> None:
    _build()
